-- Китобхона: роллар (админ / оддӣ) ва китобҳо дар база
-- Supabase → SQL Editor ичига ёпиштириб, Run босинг. Бехатар: такроран ишлатиш мумкин.

-- 1. Профиллар ва рол
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  name_key text not null unique,
  created_at timestamptz default now()
);
alter table public.profiles add column if not exists role text not null default 'user';
alter table public.profiles drop constraint if exists profiles_role_check;
alter table public.profiles add constraint profiles_role_check check (role in ('user','admin'));
alter table public.profiles enable row level security;
drop policy if exists "own read" on public.profiles;
create policy "own read" on public.profiles for select using (auth.uid() = id);
-- Эзоҳ: ҳеҷ кас аз иловаи худ рол иваз карда наметавонад (insert/update қоида нест).

-- 2. «Админ ҳастам?» санҷиш (фақат база ҳал мекунад)
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and role = 'admin')
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- 3. Китобҳо. added_by: ҳисоб нест шавад ҳам китоб мемонад («Китобхона»-и системавӣ)
create table if not exists public.books (
  id bigint generated by default as identity (start with 1000) primary key,
  t text not null,
  a text not null,
  c text not null,
  col1 text not null default '#24443a',
  col2 text not null default '#122a22',
  audio boolean not null default false,
  descr text,
  published boolean not null default true,
  added_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz default now()
);
alter table public.books enable row level security;
drop policy if exists "books read" on public.books;
drop policy if exists "books admin insert" on public.books;
drop policy if exists "books admin update" on public.books;
drop policy if exists "books admin delete" on public.books;
create policy "books read" on public.books for select using (published or public.is_admin());
create policy "books admin insert" on public.books for insert with check (public.is_admin());
create policy "books admin update" on public.books for update using (public.is_admin()) with check (public.is_admin());
create policy "books admin delete" on public.books for delete using (public.is_admin());
grant select on public.books to anon, authenticated;
grant insert, update, delete on public.books to authenticated;

-- Бахши китоб (жанр) чекловсиз: жанрҳои нав дар иловада илова мешаванд
alter table public.books drop constraint if exists books_c_check;
